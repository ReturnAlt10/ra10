"""Paper 1 Section B: short-answer questions (35 marks = 2 x 4-mark calculations + 3 x 9-mark analyse).

Calculation items carry a step-by-step AQA-style breakdown so both the local
automarker and the AI examiner can award method marks (OFR) correctly.
`check` holds the arithmetic used by build.py to verify the stated answer.
"""


def CALC(spec, data, question, answer, steps, final, unit, notes=None, marks=4, check=None, formula=None):
    return {"kind": "calc", "spec": spec, "data": data, "question": question, "answer": answer,
            "steps": steps, "final": final, "unit": unit, "notes": notes or [], "marks": marks,
            "check": check, "formula": formula}


def AN(spec, question, demands, indicative, notes=None, context=""):
    return {"kind": "analyse", "spec": spec, "context": context, "question": question, "demands": demands,
            "indicative": indicative, "notes": notes or [], "marks": 9}


