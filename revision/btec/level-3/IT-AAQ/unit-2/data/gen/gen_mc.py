def build():
    out = []
    for i, (aim, topic, question, options, ans_label, explanation) in enumerate(MC, 1):
        letters = ['A', 'B', 'C', 'D']
        items = [{'label': letters[j], 'text': options[j]} for j in range(len(options))]
        ans_idx = letters.index(ans_label)
        q = {
            'id': f'MC{i:03d}',
            'learning_aim': aim,
            'topic': topic,
            'command_verb': 'Identify',
            'marks': 1,
            'ao': 'AO1',
            'scenario': '',
            'question': question,
            'guidance': '(1)',
            'type': 'multiple_choice',
            'options': items,
            'mark_scheme': {
                'instruction': 'Award one mark for the correct option.',
                'answer': ans_label,
                'explanation': explanation,
                'points': [f'{ans_label}: {options[ans_idx]} (1)']
            }
        }
        out.append(q)
    save('mc.json', out)
    print(f'mc.json: {len(out)} questions written')


if __name__ == '__main__':
    build()