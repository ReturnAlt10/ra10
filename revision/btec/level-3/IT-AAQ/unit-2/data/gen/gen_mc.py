def build():
    out = []
    for i, (aim, topic, question, options, _ans_label, explanation) in enumerate(MC, 1):
        letters = ['A', 'B', 'C', 'D']
        # Correct option is always first in source. Rotate so the correct answer
        # lands at a varied position (not always 'A').
        n = len(options)
        k = ((i % n) or n)  # 1..n
        rotated = options[k:] + options[:k]
        correct_text = options[0]
        ans_idx = rotated.index(correct_text)
        ans_label = letters[ans_idx]
        items = [{'label': letters[j], 'text': rotated[j]} for j in range(n)]
        q = {
            'id': f'MC{i:03d}',
            'learning_aim': aim,
            'topic': topic,
            'command_verb': 'Identify',
            'marks': 1,
            'ao': 'AO1',
            'scenario': '',
            'question': question,
            'guidance': '(1)',
            'type': 'multiple_choice',
            'options': items,
            'mark_scheme': {
                'instruction': 'Award one mark for the correct option.',
                'answer': ans_label,
                'explanation': explanation,
                'points': [f'{ans_label}: {correct_text} (1)']
            }
        }
        out.append(q)
    save('mc.json', out)
    print(f'mc.json: {len(out)} questions written')


if __name__ == '__main__':
    build()