def build_quiz_items():
    out = []
    for i, (topic, question, choices, correct_index, explanation) in enumerate(ITEMS, 1):
        out.append({
            "id": f"Q{i:03d}",
            "learning_aim": topic.split(".")[0],  # A/B/C/D
            "topic": topic,
            "type": "mcq",
            "question": question,
            "choices": choices,
            "correct_index": correct_index,
            "explanation": explanation,
        })
    return out


def build_mc_items():
    """mc.json format: full question-bank structure with labelled options + mark_scheme."""
    labels = ["A", "B", "C", "D"]
    out = []
    for i, (topic, question, choices, correct_index, explanation) in enumerate(ITEMS, 1):
        options = [
            {"label": labels[j], "text": choices[j]}
            for j in range(len(choices))
        ]
        answer_label = labels[correct_index]
        out.append({
            "id": f"MC{i:03d}",
            "learning_aim": topic.split(".")[0],
            "topic": topic,
            "command_verb": "Identify",
            "marks": 1,
            "ao": "AO1",
            "scenario": "",
            "question": question,
            "guidance": "(1)",
            "type": "multiple_choice",
            "options": options,
            "mark_scheme": {
                "instruction": "Award one mark for the correct option.",
                "answer": answer_label,
                "explanation": explanation,
                "points": [f"{answer_label}: {choices[correct_index]} (1)"],
            },
        })
    return out


def main():
    base = os.path.dirname(__file__)

    quiz_items = build_quiz_items()
    with open(os.path.join(base, "quiz.json"), "w", encoding="utf-8") as f:
        json.dump(quiz_items, f, ensure_ascii=False, indent=1)
    print(f"Wrote {len(quiz_items)} MCQs to quiz.json")

    mc_items = build_mc_items()
    with open(os.path.join(base, "mc.json"), "w", encoding="utf-8") as f:
        json.dump(mc_items, f, ensure_ascii=False, indent=1)
    print(f"Wrote {len(mc_items)} MCQs to mc.json")


if __name__ == "__main__":
    main()