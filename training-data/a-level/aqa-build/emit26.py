"""Merge the AQA 7138 specimen papers + RA10 2026 papers -> revision/a-level/business-2026/js/papers-data.js"""
import json, os, re, glob, sys
sys.dont_write_bytecode = True
import build_papers as B

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'out')
TARGET = os.path.normpath(os.path.join(HERE, '..', '..', '..', 'revision', 'a-level', 'business-2026', 'js', 'papers-data.js'))
AO = {6: 'AO1 = 2, AO2 = 2, AO3 = 2', 9: 'AO1 = 2, AO2 = 2, AO3 = 2, AO4 = 3', 15: 'AO1 = 3, AO2 = 3, AO3 = 4, AO4 = 5'}
KIND = {6: 'analyse', 9: 'assess', 15: 'evaluate'}


def ao_split(s):
    return {k: int(v) for k, v in re.findall(r'(AO\d)\s*=\s*(\d+)', s or '')}


def case_name(blocks):
    for b in blocks:
        if b['t'] in ('p', 'h') and isinstance(b.get('x'), str):
            m = re.match(r'^Source [AB]:\s*(.+?)\.?$', b['x'])
            if m:
                return m.group(1).strip()
    hs = [b['x'] for b in blocks if b['t'] == 'h' and not re.match(r'^(Appendix|Source|Figure|Table)', b['x'])]
    return hs[0] if hs else ''


def main():
    papers = []
    for f in ['aqa26_specimen.json'] + [os.path.basename(x) for x in sorted(glob.glob(os.path.join(OUT, 'ra10_26_*.json')))]:
        path = os.path.join(OUT, f)
        if os.path.exists(path):
            papers += json.load(open(path, encoding='utf-8'))
    final = []
    for p in papers:
        p = dict(p)
        for it in p['items']:
            it['kind'] = KIND.get(it['marks'], it.get('kind', 'short'))
            ms = it.setdefault('ms', {})
            ms['ao'] = AO.get(it['marks'], ms.get('ao', ''))
            it['aoSplit'] = ao_split(ms['ao'])
            it['section'] = 'A' if it['main'] == 1 else 'B'
        p['cases'] = {str(k): v for k, v in p['cases'].items()}
        p['caseNames'] = [case_name(p['cases'][k]) for k in sorted(p['cases'])]
        p['twoCase'] = True
        p['total'] = 90
        p['minutes'] = 120
        n = p['paper']
        if p['source'] == 'aqa':
            p['key'] = '%s-%d' % (p['year'], n)
            p['title'] = 'Sample set 1 · Paper %d' % n
        else:
            p['key'] = '2028-%d-%s' % (n, p.get('set', 'A'))
            p['title'] = 'RA10 Paper %d · Set %s' % (n, p.get('set', 'A'))
        final.append(p)
    js = '/* AQA A-level Business (7138) papers: AQA sample assessment material (© AQA) and RA10 practice papers. Generated by training-data/a-level/aqa-build/emit26.py */\nwindow.AQA_PAPERS = %s;\n' % json.dumps(final, ensure_ascii=False, separators=(',', ':'))
    open(TARGET, 'w', encoding='utf-8').write(js)
    print('papers', len(final), 'bytes', len(js))
    for p in final:
        print(p['id'], p['title'], p['caseNames'], sum(i['marks'] for i in p['items']))


if __name__ == '__main__':
    main()
