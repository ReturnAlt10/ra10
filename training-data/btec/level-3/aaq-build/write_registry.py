"""Write the BTEC AAQ rows of the site-wide unit registry (refresh/ra10-units.js).

python write_registry.py

Replaces everything between the /* AAQ:START */ and /* AAQ:END */ markers with one row per unit found in
out/<slug>.spec.json. The registry drives the subject finder, the navbar menus and the signed-out homepage,
so run this whenever a subject or unit is added. It touches nothing else (the unit apps are built by
build_apps.py). Adding a subject: add it here AND in build_apps.py SUBJECTS – see PLAYBOOK.md.
"""
import io, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))

REGISTRY = {
    'computing-aaq': dict(name='Computing', short='Computing', color='#4f46e5',
                          keywords=['computing', 'computer science', 'programming', 'python', 'btec computing']),
    'construction-aaq': dict(name='Construction and the Built Environment', short='Construction', color='#b45309',
                             keywords=['construction', 'built environment', 'building', 'civil engineering', 'btec construction']),
    'early-childhood-development-aaq': dict(name='Early Childhood Development', short='Early Childhood', color='#db2777',
                                            keywords=['early childhood', 'early years', 'childcare', 'child development', 'children']),
    'engineering-aaq': dict(name='Engineering', short='Engineering', color='#0369a1',
                            keywords=['engineering', 'mechanical', 'electrical', 'btec engineering']),
    'health-and-social-care-aaq': dict(name='Health and Social Care', short='Health & Social Care', color='#0d9488',
                                       keywords=['health and social care', 'hsc', 'health', 'social care', 'care']),
    'medical-science-aaq': dict(name='Medical Science', short='Medical Science', color='#dc2626',
                                keywords=['medical science', 'biomedical', 'biology', 'medicine', 'human physiology']),
}
# per-unit accent so units of one subject are easy to tell apart (unit 1 uses the subject colour)
SHADES = ['', '#7c3aed', '#0891b2', '#16a34a', '#ea580c', '#9333ea', '#0f766e']


def rows():
    out = []
    for slug in sorted(REGISTRY):
        S = REGISTRY[slug]
        for u in sorted(json.load(io.open(os.path.join(HERE, 'out', slug + '.spec.json'), encoding='utf-8')), key=lambda x: x['n']):
            n = u['n']
            exam = u['type'].lower().startswith('external')
            color = S['color'] if n == 1 else (SHADES[(n - 1) % len(SHADES)] or S['color'])
            out.append('    ' + json.dumps({
                'path': '/revision/btec/level-3/%s/unit-%d' % (slug, n), 'subject': S['name'], 'qual': 'BTEC Level 3 %s (AAQ)' % S['name'],
                'short': '%s Unit %d' % (S['short'], n), 'name': 'Unit %d: %s' % (n, u['title']), 'kind': 'Exam' if exam else 'Coursework',
                'color': color, 'keywords': S['keywords'] + [u['title'].lower()], 'isNew': True}, ensure_ascii=False) + ',')
    return out


def main():
    p = os.path.join(REPO, 'refresh', 'ra10-units.js')
    s = io.open(p, encoding='utf-8', newline='').read()
    r = rows()
    block = '/* AAQ:START (generated by training-data/btec/level-3/aaq-build/write_registry.py) */\n' + '\n'.join(r) + '\n    /* AAQ:END */'
    a, b = s.find('/* AAQ:START'), s.find('/* AAQ:END */')
    if a < 0 or b < 0:
        raise SystemExit('AAQ markers missing in refresh/ra10-units.js')
    s = s[:a] + block + s[b + len('/* AAQ:END */'):]
    io.open(p, 'w', encoding='utf-8', newline='').write(s)
    print('registry: %d AAQ units written to refresh/ra10-units.js' % len(r))


if __name__ == '__main__':
    main()
